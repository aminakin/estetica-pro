<?php

namespace Local\Notifications;

use Bitrix\Main\Entity\DataManager;
use Bitrix\Main\ORM;
use Local\Notifications\DTO\Message;
use Local\Notifications\Transformers\DbTOMessageTransformer;
use Local\Notifications\Transformers\MessageToDbTransformer;

class PushNotificationTable extends DataManager
{
    public static function getTableName()
    {
        return 'b_push_notifications';
    }

    public static function getMap()
    {
        return [
            'ID' => new ORM\Fields\IntegerField(
                'ID',
                [
                    'primary' => true,
                    'autocomplete' => true,
                    'title' => 'ID',
                ],
            ),
            'USER_LIST' => new ORM\Fields\TextField(
                'USER_LIST',
                [
                    'title' => 'USER_LIST',
                ],
            ),
            'CHANNEL_LIST' => new ORM\Fields\TextField(
                'CHANNEL_LIST',
                [
                    'title' => 'CHANNEL_LIST',
                ],
            ),
            'BODY' => new ORM\Fields\TextField(
                'BODY',
                [
                    'title' => 'BODY',
                ],
            ),
            'TITLE' => new ORM\Fields\TextField(
                'TITLE',
                [
                    'title' => 'TITLE',
                ],
            ),
            'USER_PARAMS' => new ORM\Fields\TextField(
                'USER_PARAMS',
                [
                    'title' => 'USER_PARAMS',
                ],
            ),
            'DICTIONARY' => new ORM\Fields\TextField(
                'DICTIONARY',
                [
                    'title' => 'DICTIONARY',
                ],
            ),
            'DATE_INSERT' => new ORM\Fields\DatetimeField(
                'DATE_INSERT',
                [
                    'default_value' => function()
                    {
                        return new \Bitrix\Main\Type\DateTime();
                    },
                    'title' => 'DATE_INSERT',
                ],
            ),
            'DATE_EXEC' => new ORM\Fields\DatetimeField(
                'DATE_EXEC',
                [
                    'default_value' => function()
                    {
                        return new \Bitrix\Main\Type\DateTime();
                    },
                    'title' => 'DATE_EXEC',
                ],
            ),
            'SUCCESS_EXEC' => new ORM\Fields\BooleanField(
                'SUCCESS_EXEC',
                [
                    'values' => array('N', 'Y', 'E'),
                    'default_value' => 'Y',
                    'title' => 'SUCCESS_EXEC',
                ]
            ),
        ];
    }

    /**
     * @params IMessage|array $data
     */
    public static function add($data)
    {
        if ($data instanceof IMessage) {
            $data = MessageToDbTransformer::transform($data->toArray());
        }

        return parent::add($data); // TODO: Change the autogenerated stub
    }

    /**
     * @param $primary
     * @param IMessage|array $data
     * @return ORM\Data\UpdateResult
     * @throws \Exception
     */
    public static function update($primary, $data)
    {
        if ($data instanceof IMessage) {
            $data = MessageToDbTransformer::transform($data->toArray());
        }

        return parent::update($primary, $data); // TODO: Change the autogenerated stub
    }

    /**
     * @return array
     */
    public static function getMessages(array $parameters = array())
    {
        $result = [];
        $res = parent::getList($parameters);
        while($arResult = $res->fetch()) {
            $result[] = new Message(DbTOMessageTransformer::transform($arResult));
        }

        return  $result;// TODO: Change the autogenerated stub
    }
}
